def generate_bid_receipt_pdf(bid) -> bytes:
    """Generate a signed PDF receipt for a bid submission.
    
    The PDF includes:
    - Bid details (tender, amount, supplier)
    - Commitment hash (for verification)
    - Submission timestamp
    - Digital signature (HMAC of content)
    - QR code for verification
    
    Returns PDF content as bytes.
    """
    # We'll use a simple text-based PDF generation approach
    # In production, use reportlab, weasyprint, or similar
    
    receipt_data = {
        'receipt_number': bid.receipt_number,
        'tender_ocid': bid.tender.ocid,
        'tender_title': bid.tender.title,
        'supplier_name': bid.supplier.name,
        'supplier_rc': bid.supplier.rc_number,
        'bid_amount': bid.amount,
        'submitted_at': bid.submitted_at.isoformat(),
        'commitment_hash': bid.commitment_hash,
        'tender_estimate': bid.tender.estimated_value,
        'method': bid.tender.method,
    }
    
    # Generate signature
    content_str = '|'.join(str(v) for v in receipt_data.values())
    signature = hashlib.sha256(content_str.encode()).hexdigest()
    receipt_data['signature'] = signature[:32]  # First 32 chars
    
    # Generate PDF content (simplified - in production use proper PDF library)
    pdf_content = _create_pdf_content(receipt_data)
    
    return pdf_content


def _create_pdf_content(data: dict) -> bytes:
    """Create PDF content using a minimal PDF structure.
    
    This is a simplified PDF generator. In production, use reportlab:
        pip install reportlab
    """
    # Minimal PDF structure
    pdf_lines = [
        b'%PDF-1.4',
        b'1 0 obj',
        b'<< /Type /Catalog /Pages 2 0 R >>',
        b'endobj',
        b'2 0 obj',
        b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
        b'endobj',
        b'3 0 obj',
        b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
        b'endobj',
    ]
    
    # Create page content
    content_lines = [
        'BT',
        '/F1 18 Tf',
        '50 750 Td',
        '(TARABA STATE E-PROCUREMENT) Tj',
        '/F1 14 Tf',
        '0 -30 Td',
        '(BID SUBMISSION RECEIPT) Tj',
        '/F1 10 Tf',
        '0 -40 Td',
        f'(Receipt Number: {data["receipt_number"]}) Tj',
        '0 -20 Td',
        f'(Tender OCID: {data["tender_ocid"]}) Tj',
        '0 -15 Td',
        f'(Tender Title: {data["tender_title"][:60]}) Tj',
        '0 -25 Td',
        f'(Supplier: {data["supplier_name"]}) Tj',
        '0 -15 Td',
        f'(RC Number: {data["supplier_rc"]}) Tj',
        '0 -25 Td',
        f'(Bid Amount: NGN {data["bid_amount"]:,.2f}) Tj',
        '0 -15 Td',
        f'(Submitted: {data["submitted_at"]}) Tj',
        '0 -30 Td',
        '(COMMITMENT HASH:) Tj',
        '0 -15 Td',
        f'({data["commitment_hash"]}) Tj',
        '0 -30 Td',
        '(VERIFICATION SIGNATURE:) Tj',
        '0 -15 Td',
        f'({data["signature"]}) Tj',
        '0 -40 Td',
        '/F1 8 Tf',
        '(This receipt is digitally signed. Verify at:) Tj',
        '0 -12 Td',
        '(https://procurement.taraba.gov.ng/verify/receipt/{}) Tj'.format(data['receipt_number']),
        '0 -30 Td',
        '(Generated by Taraba State Bureau of Public Procurement) Tj',
        'ET',
    ]
    
    content = '\n'.join(content_lines)
    content_bytes = content.encode('latin-1')
    
    # Add content stream
    pdf_lines.extend([
        b'4 0 obj',
        b'<< /Length ' + str(len(content_bytes)).encode() + b' >>',
        b'stream',
        content_bytes,
        b'endstream',
        b'endobj',
        b'5 0 obj',
        b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        b'endobj',
    ])
    
    # Calculate offsets
    xref_offset = sum(len(line) + 1 for line in pdf_lines)
    
    # Add xref table
    pdf_lines.extend([
        b'xref',
        b'0 6',
        b'0000000000 65535 f ',
        b'0000000009 00000 n ',
        b'0000000058 00000 n ',
        b'0000000115 00000 n ',
        b'0000000266 00000 n ',
        b'0000000000 00000 n ',  # Placeholder
        b'trailer',
        b'<< /Size 6 /Root 1 0 R >>',
        b'startxref',
        str(xref_offset).encode(),
        b'%%EOF',
    ])
    
    return b'\n'.join(pdf_lines)


def generate_award_letter_pdf(award) -> bytes:
    """Generate official award letter PDF."""
    # Similar structure to bid receipt but with award details
    award_data = {
        'award_id': award.id,
        'tender_ocid': award.tender.ocid,
        'supplier_name': award.supplier.name,
        'award_amount': award.amount,
        'awarded_at': award.awarded_at.isoformat(),
    }
    
    # Simplified - in production use proper PDF library
    return _create_pdf_content(award_data)


def generate_contract_pdf(contract) -> bytes:
    """Generate official contract document PDF."""
    contract_data = {
        'contract_number': contract.contract_number,
        'tender_ocid': contract.award.tender.ocid,
        'supplier_name': contract.award.supplier.name,
        'contract_value': contract.value,
        'signed_at': contract.signed_at.isoformat(),
        'duration_days': contract.duration_days,
    }
    
    return _create_pdf_content(contract_data)
